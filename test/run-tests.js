const assert = require('assert');
const fs = require('fs');
const path = require('path');
const { convert, parseMarkdown, findChromeExecutable } = require('../src/index');

async function runTests() {
  console.log('🧪 Running md-to-pdf-lite Test Suite...\n');

  // Test 1: Chrome Finder
  console.log('Test 1: Auto-detect Chrome/Chromium executable');
  const chrome = findChromeExecutable();
  assert.ok(chrome, 'Chrome executable should be found');
  assert.ok(fs.existsSync(chrome), `Chrome path should exist: ${chrome}`);
  console.log('  ✔ Chrome detected:', chrome);

  // Test 2: Markdown Parsing
  console.log('Test 2: Markdown parser features');
  const sampleMd = `
# Title
| Header 1 | Header 2 |
| :--- | :--- |
| Cell 1 | Cell 2 |

\`\`\`javascript
const a = 1;
\`\`\`


Formula: $E = mc^2$

\`\`\`mermaid
graph TD; A-->B;
\`\`\`

<!-- pagebreak -->

Page 2 content.
`;
  const html = parseMarkdown(sampleMd);
  assert.ok(html.includes('<table>'), 'Should contain table HTML');
  assert.ok(html.includes('class="hljs'), 'Should contain highlighted code');
  assert.ok(html.includes('class="katex"'), 'Should render KaTeX formula');
  assert.ok(html.includes('class="mermaid"'), 'Should render mermaid block');
  // Verify preprocessMarkdown code block immunity
  const { preprocessMarkdown } = require('../src/index');
  const codeImmunityMd = 'Explain: `<!-- pagebreak -->` and `---pagebreak---`\n\n```\n<!-- pagebreak -->\n```\n\n<!-- pagebreak -->\n\nReal break';
  const preprocessed = preprocessMarkdown(codeImmunityMd);
  assert.ok(preprocessed.includes('`<!-- pagebreak -->`'), 'Inline code must remain intact');
  assert.ok(preprocessed.includes('`---pagebreak---`'), 'Inline pagebreak syntax must remain intact');
  assert.ok(preprocessed.includes('```\n<!-- pagebreak -->\n```'), 'Fenced code block pagebreak must remain intact');
  assert.ok(preprocessed.includes('<div class="page-break"></div>\n\nReal break'), 'Standalone pagebreak must be converted');

  // Verify dark code theme flag parsing (:dark and dark)
  const darkMd = '```typescript:dark\nconst a = 1;\n```\n\n```python dark\nb = 2\n```';
  const darkHtml = parseMarkdown(darkMd);
  assert.ok(darkHtml.includes('class="hljs code-theme-dark"'), 'Should support :dark suffix');
  assert.ok(darkHtml.includes('data-theme="dark"'), 'Should add data-theme="dark" attribute');

  // Verify CJK bold emphasis spacing normalization (e.g. 直前に**「重要」**)
  const cjkBoldMd = '漏水調査の直前に**「予防保全として漏水調査を実施していますか？（はい/いいえ）」**\n\n直前に**【重要項目】**です。\n\nコード: `const x = a ** b;`';
  const cjkBoldHtml = parseMarkdown(cjkBoldMd);
  assert.ok(cjkBoldHtml.includes('<strong>「予防保全として漏水調査を実施していますか？（はい/いいえ）」</strong>'), 'CJK bold with open/close brackets must render as <strong>');
  assert.ok(cjkBoldHtml.includes('<strong>【重要項目】</strong>'), 'CJK bold with brackets must render as <strong>');
  assert.ok(cjkBoldHtml.includes('<code>const x = a ** b;</code>'), 'Code block with ** must not be modified');

  console.log('  ✔ Parser correctly handles tables, code, KaTeX, Mermaid, page breaks, code immunity, and CJK bold typography');

  const { verifyPdf } = require('./pdf-verifier');

  // Test 3: PDF Generation & Verification
  console.log('Test 3: Convert markdown to PDF buffer & verify content');
  const result = await convert({
    markdown: '# Test PDF\n\nGenerated by md-to-pdf-lite test suite.',
    format: 'A4'
  });
  const v3 = await verifyPdf(result.buffer, {
    exactPages: 1,
    mustContain: ['Test PDF', 'Generated by md-to-pdf-lite']
  });
  console.log(`  ✔ PDF verified: ${v3.pageCount} page, ${v3.byteSize} bytes`);

  // Test 4: Mermaid Diagram PDF Rendering & Verification
  console.log('Test 4: Render Markdown with Mermaid flowchart to PDF & verify vector nodes');
  const mermaidResult = await convert({
    markdown: '# Architecture\n\n```mermaid\ngraph LR\nClient --> Server\nServer --> Database\n```\n',
    format: 'A4'
  });
  const v4 = await verifyPdf(mermaidResult.buffer, {
    minPages: 1,
    mustContain: ['Architecture', 'Client', 'Server', 'Database'],
    mustNotContain: ['graph LR', 'style A fill:'],
    expectMermaid: true,
    mermaidNodeLabels: ['Client', 'Server', 'Database']
  });
  console.log(`  ✔ Mermaid flowchart verified: nodes compiled into vector diagram (${v4.byteSize} bytes)`);

  // Test 5: Clean Business Theme Rendering
  console.log('Test 5: Render Markdown with clean borderless table theme');
  const cleanResult = await convert({
    markdown: '# Proposal\n\n| Service | Cost |\n| :--- | ---: |\n| Cloud | $500 |\n',
    theme: 'clean',
    format: 'A4'
  });
  const v5 = await verifyPdf(cleanResult.buffer, {
    exactPages: 1,
    mustContain: ['Proposal', 'Service', 'Cost', 'Cloud', '$500']
  });
  console.log(`  ✔ Clean business theme verified: table content verified (${v5.byteSize} bytes)`);

  // Test 6: Corporate Japan Theme Rendering
  console.log('Test 6: Render Markdown with corporate Japanese business theme');
  const jaResult = await convert({
    markdown: '# 御見積書\n\n| 項目 | 金額 |\n| :--- | ---: |\n| クラウド運用費 | ¥100,000 |\n',
    theme: 'corporate-ja',
    format: 'A4'
  });
  const v6 = await verifyPdf(jaResult.buffer, {
    exactPages: 1,
    mustContain: ['御見積書', '項目', '金額', 'クラウド運用費', '¥100,000']
  });
  console.log(`  ✔ Corporate Japanese business theme verified: CJK text verified (${v6.byteSize} bytes)`);

  console.log('\n🎉 All tests passed successfully!\n');
}

runTests().catch(err => {
  console.error('\n❌ Test suite failed:', err);
  process.exit(1);
});
